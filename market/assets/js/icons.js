const DEFAULT_ICON = 'info';

/** 返回一个 span.icon 包裹的内联 SVG（name 仅允许内置名，未知回退 info） */
export function icon(name, size = 18, className = '') {
  const key = ALIASES[name] || name;
  const inner = ICONS[key] || ICONS[DEFAULT_ICON];
  const span = document.createElement('span');
  span.className = `icon${className ? ` ${className}` : ''}`;
  span.setAttribute('aria-hidden', 'true');
  span.innerHTML = `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" xmlns="http://www.w3.org/2000/svg">${inner}</svg>`;
  return span;
}

